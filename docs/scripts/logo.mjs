/**
 * Generates public/logo.svg — the static mark used as the favicon.
 *
 * SVG has no loop primitive, and a <script> inside the file is not executed
 * when the file is loaded as a favicon or as an <img src>, so the string count
 * cannot be a live parameter of the document. It is a parameter of this
 * generator instead: change STITCHES (or pass it on the command line) and
 * re-run.
 *
 *   node scripts/logo.mjs           # default
 *   node scripts/logo.mjs 68        # 68 divisions per side -> 201 strings
 *
 * The in-page mark is the <Logo> component, which takes the same count as a
 * `stitches` prop and needs no regeneration.
 */
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Divisions per triangle side. Each side contributes STITCHES - 1 strings. */
const STITCHES = Number(process.argv[2] ?? 68);

/** Triangle geometry, in viewBox units: equilateral, apex pointing down. */
const SIDE = 576;
const MARGIN = 40;

/** Ink, and the plate it is printed on. Set BACKGROUND to null for none. */
const INK = '#C9C9C4';
const BACKGROUND = '#09090B';
const OPACITY = 1;

/**
 * Stroke weight is not scale-invariant: at 24 divisions a 2px string reads as
 * a drawing, and at 68 the same weight silts the mesh up into a solid. Pin it
 * to the gap between neighbouring strings instead.
 */
const WEIGHT_RATIO = 4 / (SIDE / 24);
const EDGE_RATIO = 2;

if (!Number.isInteger(STITCHES) || STITCHES < 2) {
  throw new Error(`STITCHES must be an integer >= 2, got ${process.argv[2]}`);
}

const round = (n) => Number(n.toFixed(3));

const HEIGHT = (SIDE * Math.sqrt(3)) / 2;
const A = { x: MARGIN, y: MARGIN };
const B = { x: A.x + SIDE, y: A.y };
const C = { x: A.x + SIDE / 2, y: A.y + HEIGHT };

/** The mark's own bounds, padded equally on every side. */
const WIDTH = SIDE + MARGIN * 2;
const VIEW_H = Math.ceil(HEIGHT + MARGIN * 2);

const lerp = (p, q, t) => ({ x: p.x + (q.x - p.x) * t, y: p.y + (q.y - p.y) * t });

/**
 * One fan: every division point on A→B joined to its mirror on A→C, so the
 * straight strings envelope a parabola. Two rotations about the centroid give
 * the other two corners, which is why only one fan is emitted.
 */
const fan = [];
for (let i = 1; i < STITCHES; i++) {
  const u = i / STITCHES;
  const from = lerp(A, B, u);
  const to = lerp(A, C, 1 - u);
  fan.push(
    `        M ${round(from.x)} ${round(from.y)} L ${round(to.x)} ${round(to.y)}`,
  );
}

const centroid = {
  x: round((A.x + B.x + C.x) / 3),
  y: round((A.y + B.y + C.y) / 3),
};

const weight = Math.max(0.35, round((SIDE / STITCHES) * WEIGHT_RATIO));
const edge = round(weight * EDGE_RATIO);

const plate = BACKGROUND
  ? `\n  <!-- Remove this rectangle for a transparent background. -->\n  <rect width="${WIDTH}" height="${VIEW_H}" fill="${BACKGROUND}"/>\n`
  : '';

const svg = `<svg xmlns="http://www.w3.org/2000/svg"
     viewBox="0 0 ${WIDTH} ${VIEW_H}"
     width="${WIDTH}"
     height="${VIEW_H}"
     role="img"
     aria-labelledby="title desc">
  <title id="title">Triangular string-art icon</title>
  <desc id="desc">
    A symmetric triangular mesh made from three rotated families of straight
    lines, ${STITCHES} divisions per side.
  </desc>

  <!-- Generated by scripts/logo.mjs — edit STITCHES there, not here. -->
${plate}
  <g fill="none"
     stroke="${INK}"
     opacity="${OPACITY}"
     stroke-linecap="round"
     stroke-linejoin="round">

    <path stroke-width="${edge}" d="
      M ${round(A.x)} ${round(A.y)}
      L ${round(B.x)} ${round(B.y)}
      L ${round(C.x)} ${round(C.y)}
      Z
    "/>

    <defs>
      <path id="fan" d="
${fan.join('\n')}
      "/>
    </defs>

    <g stroke-width="${weight}">
      <use href="#fan"/>
      <use href="#fan" transform="rotate(120 ${centroid.x} ${centroid.y})"/>
      <use href="#fan" transform="rotate(240 ${centroid.x} ${centroid.y})"/>
    </g>
  </g>
</svg>
`;

const out = resolve(dirname(fileURLToPath(import.meta.url)), '../public/logo.svg');
writeFileSync(out, svg);

console.log(
  `logo.svg: ${STITCHES} divisions/side, ${3 * (STITCHES - 1)} strings, ` +
    `stroke ${weight} (edge ${edge})`,
);
