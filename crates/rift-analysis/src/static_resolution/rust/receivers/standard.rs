    use super::{Shared, Unique};

    #[test]
    fn rows_are_ordered_for_binary_search() {
        for (types, _, members) in super::METHODS {
            assert!(types.is_sorted(), "{types:?}");
            assert!(members.is_sorted(), "{members:?}");
        }
    }

    #[test]
    fn methods_are_found_by_the_type_that_declares_them() {
        for (name, member, expected) in [
            ("slice", "len", &[&[Shared][..]][..]),
            ("slice", "reverse", &[&[Unique][..]]),
            ("slice", "split_off_first", &[&[Unique, Shared][..]]),
            ("slice:u8", "is_ascii", &[&[Shared][..]]),
            ("array", "map", &[&[][..]]),
            ("str", "trim", &[&[Shared][..]]),
            ("u32", "count_ones", &[&[][..]]),
            ("u8", "is_ascii", &[&[Shared][..]]),
            ("char", "is_alphabetic", &[&[][..]]),
            ("bool", "then_some", &[&[][..]]),
            ("vec::Vec", "push", &[&[Unique][..]]),
            ("string::String", "len", &[&[Shared][..]]),
            ("option::Option", "is_some", &[&[Shared][..]]),
            ("result::Result", "is_ok", &[&[Shared][..]]),
            ("pointer", "is_null", &[&[][..]]),
            // Declared for another element type, for the slice an array becomes, for another
            // type, only in unstable form, or not at all.
            ("slice", "is_ascii", &[]),
            ("array", "len", &[]),
            ("vec::Vec", "first", &[]),
            ("slice", "partition_dedup", &[]),
            ("slice", "beacon", &[]),
            ("boxed::Box", "len", &[]),
        ] {
            let found = super::receivers(name, member).collect::<Vec<_>>();
            assert_eq!(found, expected, "{name} {member}");
        }
    }
