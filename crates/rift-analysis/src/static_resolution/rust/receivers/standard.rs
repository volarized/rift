//! Inherent methods of the types the Rust standard library provides.
//!
//! The rows are the stable inherent methods with a `self` parameter of every primitive,
//! struct, enum and union in the documentation of `std` 1.98.1. The compiler passes over an
//! unstable method when a trait method of the name applies, so unstable methods are absent.
//! Types are named by their path in `std`, primitives by their own name. `slice:X` and
//! `array:X` hold methods of slices and arrays of the element type `X` alone.
//!
//! `rift-dev standard-methods <folder of rustdoc pages>` writes the rows and the release above
//! from the `rust-docs` component of a toolchain. The rows decide alone: no toolchain is read
//! when Rift is built or runs. A method `std` gains in a later release is absent, so a call of
//! it names the package trait method of that name until the rows are written again.

use super::Reference::{self, Shared, Unique};

/// Types, what `self` adds in front of the type, and the methods that take it so.
type Methods = (
    &'static [&'static str],
    &'static [Reference],
    &'static [&'static str],
);

/// What `self` adds in front of `name` in each method `member` of the standard type `name`.
pub(super) fn receivers(name: &str, member: &str) -> impl Iterator<Item = &'static [Reference]> {
    METHODS
        .iter()
        .filter(move |(types, _, members)| {
            members.binary_search(&member).is_ok() && types.binary_search(&name).is_ok()
        })
        .map(|(_, receiver, _)| *receiver)
}

