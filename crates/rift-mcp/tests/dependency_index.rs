#[tokio::test]
async fn a_global_search_answers_the_package_declaration_by_unit() -> TestResult {
    let workspace = served_dependent_workspace(None).await?;
    let (_directory, client, server_task) = workspace.served;
    helper_indexed(&client).await?;

    let answer = search(
        &client,
        json!({ "query": "helper_beacon", "scope": "global" }),
    )
    .await?;

    let results = answer["results"].as_array().ok_or("results are an array")?;
    // The precise phase places the declaration the query names; the widened phase
    // then fills the pool with the package's other `helper` declarations, which is
    // the same order the project's own store answers in.
    let hit = &results[0];
    assert_one_location(hit);
    assert_eq!(hit["unit"], json!(HELPER_UNIT), "{hit:#}");
    // The identifier ranking placed it by name and the package's own full-text
    // ranking placed it again through the signature and the declaration source.
    assert_eq!(
        hit["matched_by"],
        json!(["name", "signature", "content"]),
        "{hit:#}"
    );
    assert_eq!(hit["hit"]["target"], json!("symbol"), "{hit:#}");
    assert_eq!(
        hit["hit"]["symbol"]["name"],
        json!("helper_beacon"),
        "{hit:#}"
    );
    assert_eq!(
        hit["hit"]["symbol"]["origin"]["location"],
        json!("dependency"),
        "{hit:#}"
    );
    assert_eq!(hit["line"], json!(1), "{hit:#}");
    assert!(
        hit.get("source").is_none() && hit.get("score").is_none(),
        "an omitted include attaches neither excerpt nor score: {hit:#}"
    );
    assert!(
        hit.get("traversal_path").is_none() && hit.get("distance").is_none(),
        "a lexical hit carries no walk: {hit:#}"
    );
    assert!(
        answer["warnings"]
            .as_array()
            .into_iter()
            .flatten()
            .all(|warning| warning["package"]["name"] != json!("helper")),
        "an indexed package is never reported skipped: {answer:#}"
    );

    client.cancel().await?;
    server_task.await?;
    Ok(())
}

#[tokio::test]
async fn the_all_scope_search_answers_local_and_package_hits() -> TestResult {
    let workspace = served_dependent_workspace(None).await?;
    let (_directory, client, server_task) = workspace.served;
    helper_indexed(&client).await?;

    let answer = search(
        &client,
        json!({
            "query": "beacon",
            "scope": "all",
            "target": "symbol",
            "include": ["source"],
            "limit": 10
        }),
    )
    .await?;

    let located = located_names(&answer);
    for expected in [
        ("beacon".to_owned(), false),
        ("beacon".to_owned(), true),
        ("helper_beacon".to_owned(), true),
    ] {
        assert!(located.contains(&expected), "{expected:?} {answer:#}");
    }
    let results = answer["results"].as_array().ok_or("results are an array")?;
    for hit in results {
        assert_one_location(hit);
        assert!(hit["source"].is_string(), "{hit:#}");
    }
    let project = results
        .iter()
        .find(|hit| hit.get("path").is_some())
        .ok_or("the project hit is addressed by path")?;
    assert_eq!(project["path"], json!("src/lib.rs"), "{project:#}");

    client.cancel().await?;
    server_task.await?;
    Ok(())
}

#[tokio::test]
async fn a_global_search_reaches_a_package_declaration_through_its_documentation() -> TestResult {
    // The query shares no word with the declaration's name, so the identifier
    // ranking cannot place it. Only the package's own full-text ranking can,
    // which is the input this scope gained.
    let workspace = served_dependent_workspace(None).await?;
    let (_directory, client, server_task) = workspace.served;
    helper_indexed(&client).await?;

    let answer = search(
        &client,
        json!({ "query": "harbour pilots", "scope": "global" }),
    )
    .await?;

    let results = answer["results"].as_array().ok_or("results are an array")?;
    assert_eq!(results.len(), 1, "{answer:#}");
    let hit = &results[0];
    assert_eq!(hit["unit"], json!(HELPER_UNIT), "{hit:#}");
    assert_eq!(
        hit["hit"]["symbol"]["name"],
        json!("helper_lantern"),
        "{hit:#}"
    );
    // The declaration's own source carries the doc comment too, so both columns
    // placed it.
    assert_eq!(
        hit["matched_by"],
        json!(["documentation", "content"]),
        "{hit:#}"
    );

    client.cancel().await?;
    server_task.await?;
    Ok(())
}

