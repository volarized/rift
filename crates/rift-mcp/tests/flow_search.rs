fn sparql(query: String) -> QueryParams {
    QueryParams {
        include: rift_protocol::query::QueryInclude::default(),
        max_results: 10,
        query,
        language: QueryLanguage::Sparql,
        ..Default::default()
    }
}

fn flows(slice: &str) -> QueryParams {
    sparql(format!(
        "SELECT ?flow ?score ?index ?symbol {{
           SERVICE :flows {{
             ?flow :query '{SEED}'; :max_results 1; :score ?score; :steps ?step .
             ?step :index ?index; :value ?symbol
           }}
         }} ORDER BY DESC(?score) ?flow ?index {slice}"
    ))
}

fn step(row: &Value) -> TestResult<(u64, &str)> {
    Ok((literal(row, "index")?.parse()?, iri(row, "symbol")?))
}

fn assert_steps(answer: &Value, expected: &[(u64, &str)]) -> TestResult {
    let rows = rows(answer)?;
    let actual = rows.iter().map(step).collect::<TestResult<Vec<_>>>()?;
    assert_eq!(actual, expected, "flow steps: {answer}");
    let first = rows.first().ok_or("a matched flow must have a step")?;
    let score = literal(first, "score")?.parse::<f64>()?;
    assert!(score.is_finite() && score > 0.0, "flow score: {first}");
    assert!(first["flow"].is_object(), "flow identity: {first}");
    for row in rows {
        assert_eq!(row["flow"], first["flow"], "flow identity: {row}");
        assert_eq!(row["score"], first["score"], "flow score: {row}");
    }
    Ok(())
}

#[tokio::test]
async fn static_javascript_finds_a_path_around_the_ranked_middle_step() -> TestResult {
    let files = [(JAVASCRIPT_PATH, JAVASCRIPT_SOURCE)];
    let (_fixture, client, task) = served_workspace(&files, None).await?;
    let entry = captured_seed(&client, "entry", JAVASCRIPT_PATH).await?;
    let middle = captured_seed(&client, "middle", JAVASCRIPT_PATH).await?;
    let finish = captured_seed(&client, "finish", JAVASCRIPT_PATH).await?;
    let ranked = sparql(format!(
        "SELECT ?symbol ?score {{ SERVICE :search {{
           ?hit :query '{SEED}'; :target 'symbol'; :max_results 32; :symbol ?symbol; :score ?score
         }} }}"
    ));
    let ranked = query_after_population(&client, &ranked).await?;
    let ranked_rows = rows(&ranked)?;
    assert_eq!(ranked_rows.len(), 1, "ranked seed: {ranked}");
    assert_eq!(iri(&ranked_rows[0], "symbol")?, middle);

    let answer = query_after_population(&client, &flows("")).await?;
    let expected = [
        (0, entry.as_str()),
        (1, middle.as_str()),
        (2, finish.as_str()),
    ];
    assert_steps(&answer, &expected)?;

    let seed_score = literal(&ranked_rows[0], "score")?.parse::<f64>()?;
    let flow_score = literal(&rows(&answer)?[0], "score")?.parse::<f64>()?;
    assert_eq!(
        flow_score.to_bits(),
        seed_score.to_bits(),
        "score from one matched seed"
    );

    let sliced = query_after_population(&client, &flows("LIMIT 1 OFFSET 1")).await?;
    assert_steps(&sliced, &[(1, middle.as_str())])?;
    assert_javascript_evidence(&client).await?;
    assert_repeated_flow_service_join(&client).await?;
    client.cancel().await?;
    task.await?;
    Ok(())
}

async fn assert_javascript_evidence(
    client: &rmcp::service::RunningService<rmcp::RoleClient, ()>,
) -> TestResult {
    let mut query = sparql(format!(
        "SELECT ?step ?index ?name ?unit ?start ?end {{
           SERVICE :flows {{
             ?flow :query '{SEED}'; :max_results 1; :steps ?step .
             ?step :index ?index; :value ?symbol;
                   :evidence [ :range [ :unit ?unit; :start ?start; :end ?end ] ]
           }}
           ?symbol :name ?name
         }} ORDER BY ?index ?start"
    ));
    let answer = query_after_population(client, &query).await?;
    let bindings = rows(&answer)?;
    let sites = JAVASCRIPT_SOURCE
        .match_indices("middle();")
        .map(|(start, _)| start);
    let outgoing = JAVASCRIPT_SOURCE
        .find("finish(\"")
        .ok_or("fixture's outgoing call")?;
    let expected = sites
        .map(|start| (1, "middle", start))
        .chain([(2, "finish", outgoing)]);
    let actual = bindings
        .iter()
        .map(call_site)
        .collect::<TestResult<Vec<_>>>()?;
    assert_eq!(
        actual,
        expected.collect::<Vec<_>>(),
        "flow evidence: {answer}"
    );
    assert!(
        bindings
            .iter()
            .all(|row| row["step"].get("providers").is_none())
    );
    query
        .include
        .insert(rift_protocol::query::QuerySection::Providers);
    let included = query_after_population(client, &query).await?;
    let included = rows(&included)?;
    assert_eq!(included.len(), bindings.len());
    for row in included {
        assert_eq!(row["step"]["providers"], serde_json::json!(["static"]));
    }
    Ok(())
}

fn call_site(row: &Value) -> TestResult<(u64, &str, usize)> {
    let unit = format!("rift://source/project/{JAVASCRIPT_PATH}");
    assert_eq!(iri(row, "unit")?, unit);
    let name = literal(row, "name")?;
    let start = literal(row, "start")?.parse()?;
    let end = literal(row, "end")?.parse()?;
    let source = JAVASCRIPT_SOURCE
        .get(start..end)
        .ok_or("call site range in fixture source")?;
    assert!(source.starts_with(name), "call site for {name}: {source}");
    Ok((literal(row, "index")?.parse()?, name, start))
}

async fn assert_repeated_flow_service_join(
    client: &rmcp::service::RunningService<rmcp::RoleClient, ()>,
) -> TestResult {
    let query = sparql(format!(
        "SELECT ?flow ?left ?right {{
           SERVICE :flows {{ ?flow :query '{SEED}'; :max_results 1; :score ?left }}
           SERVICE :flows {{ ?flow :query '{SEED}'; :max_results 1; :score ?right }}
         }}"
    ));
    let answer = query_after_population(client, &query).await?;
    let [joined] = rows(&answer)? else {
        return Err(format!("expected one joined flow: {answer}").into());
    };
    assert!(joined["flow"].is_object(), "joined flow identity: {joined}");
    assert_eq!(literal(joined, "left")?, literal(joined, "right")?);
    Ok(())
}

#[tokio::test]
async fn static_rust_reads_steps_across_pages() -> TestResult {
    let files = rust_files(RUST_SOURCE);
    let (_fixture, client, task) =
        served_workspace(&files, Some(QUERY_CONFIGURATION.to_owned())).await?;
    let entry = captured_seed(&client, "entry", RUST_PATH).await?;
    let middle = captured_seed(&client, "middle", RUST_PATH).await?;
    let finish = captured_seed(&client, "finish", RUST_PATH).await?;
    let parameters = QueryParams {
        include: rift_protocol::query::QueryInclude::default(),
        max_results: 2,
        ..flows("")
    };
    let first = query_after_population(&client, &parameters).await?;
    assert_steps(&first, &[(0, entry.as_str()), (1, middle.as_str())])?;
    let request = workspace_client::query::result_page(&parameters, &first, 2)?;
    let next = query_after_population(&client, &request).await?;
    assert_steps(&next, &[(2, finish.as_str())])?;
    assert_eq!(rows(&first)?[0]["flow"], rows(&next)?[0]["flow"]);
    assert_eq!(rows(&first)?[0]["score"], rows(&next)?[0]["score"]);
    client.cancel().await?;
    task.await?;
    Ok(())
}

