async fn assert_full_flow(workspace: ServedWorkspace, path: &str) -> TestResult {
    let (_fixture, client, task) = workspace;
    let entry = captured_seed(&client, "entry", path).await?;
    let middle = captured_seed(&client, "middle", path).await?;
    let finish = captured_seed(&client, "finish", path).await?;
    let answer = query_after_population(&client, &flows("")).await?;
    let expected = [
        (0, entry.as_str()),
        (1, middle.as_str()),
        (2, finish.as_str()),
    ];
    assert_steps(&answer, &expected)?;
    client.cancel().await?;
    task.await?;
    Ok(())
}
