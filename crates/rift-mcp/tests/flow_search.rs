#[tokio::test]
async fn static_rust_reports_partial_coverage_for_an_inferred_receiver() -> TestResult {
    let files = rust_files(RUST_MIXED_SOURCE);
    let (_fixture, client, task) = served_workspace(&files, None).await?;
    let entry = captured_seed(&client, "entry", RUST_PATH).await?;
    let middle = captured_seed(&client, "middle", RUST_PATH).await?;
    let (partial, warnings) =
        workspace_client::populated_answer(&client, "search", &serde_json::to_value(flows(""))?)
            .await?;
    assert!(partial.get("warnings").is_none());
    assert_steps(&partial, &[(0, entry.as_str()), (1, middle.as_str())])?;
    assert!(
        warnings
            .iter()
            .any(|warning| warning["code"] == "edge_coverage_missing"),
        "partial flow must report unavailable call coverage: {partial}"
    );

    let count = sparql(format!(
        "SELECT (COUNT(?flow) AS ?count) {{ SERVICE :flows {{ ?flow :query '{SEED}' }} }}"
    ));
    let count = query_after_population(&client, &count).await?;
    assert_eq!(count["outcome"], "unavailable", "partial count: {count}");
    assert_eq!(
        count["reason"], "insufficient_coverage",
        "partial count: {count}"
    );
    let tools = client.list_all_tools().await?;
    let schema = tools
        .iter()
        .find(|tool| tool.name == "search")
        .and_then(|tool| tool.output_schema.as_deref())
        .ok_or("search must advertise its output schema")?;
    let validator = jsonschema::validator_for(&Value::Object(schema.clone()))?;
    for answer in [&partial, &count] {
        validator
            .validate(answer)
            .map_err(|error| error.to_string())?;
    }

    client.cancel().await?;
    task.await?;
    Ok(())
}

